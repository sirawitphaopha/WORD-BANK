#!/usr/bin/env bash
# 🎫 สร้าง "ตั๋ว push" 1 ใบ — ใช้ได้ครั้งเดียว แล้วถูกลบทันทีที่ push
#
# ⛔ รันสคริปต์นี้ได้เฉพาะตอนพี่กันพิมพ์คำว่า "push / พุช" ตรง ๆ ในข้อความล่าสุดเท่านั้น
#    ห้ามรันเพราะ: พี่กันเคยสั่ง push เมื่อกี้ / พี่กันบอก "เอาขึ้น main" / งานเสร็จแล้วน่าจะ push ได้
#    1 ครั้งที่พี่กันสั่ง = ตั๋ว 1 ใบ = push ได้ 1 ครั้ง
#
# 🔴 ที่มา: 25 ก.ค. 2569 พี่กันพิมพ์ "พุช" ครั้งเดียว แคลร์ push ไป 7 ครั้ง (เกินมา 6)
#    กฎเป็นตัวหนังสือไม่พอ ต้องให้เครื่องบล็อก (ดู .claude/hooks/pre-git.sh)
set -euo pipefail
root="$(git rev-parse --git-dir 2>/dev/null || echo .git)"
: > "$root/PUSH-OK"
echo "🎫 สร้างตั๋ว push แล้ว 1 ใบ ($root/PUSH-OK)"
echo "   push ได้ 1 ครั้ง · ตั๋วจะถูกลบทันทีที่ push"
echo "   🔁 คำสั่ง push 1 ครั้งของพี่กัน = flow 4 ขั้น ครอบคลุมการ push ไฟล์ SESSION ด้วย"
echo "      1 อัปเดต CLAUDE.md + README → 2 commit → 3 push ขึ้น main"
echo "      4 เขียน docs/SESSION-YYYY-MM-DD.md แล้ว **ขอตั๋วใบใหม่ที่นี่แล้ว push ตามทันที**"
echo "   🛑 ห้ามหยุดรอให้พี่กันสั่ง push ซ้ำเพื่อส่งไฟล์ SESSION — ขั้นที่ 4 อยู่ในคำสั่งเดิมแล้ว"
