PF = ('subpath', 'subpaths', 'all_paths')


def paths_of(w):
    out = []
    for p in (w.get('all_paths') or []):
        out.append(p.get('path') if isinstance(p, dict) else p)
    return out


def set_paths(w, paths, cat_of):
    """เขียนกิ่งกลับลงทุกช่อง · subpaths เก็บเฉพาะกิ่งในหมวดของคำ (ตามโครง DB ปัจจุบัน)"""
    cid = w.get('category_id')
    w['all_paths'] = [{'category_id': cat_of.get(p, cid), 'path': p} for p in paths]
    same = [p for p in paths if cat_of.get(p) == cid]
    w['subpaths'] = same or paths[:1]
    w['subpath'] = w['subpaths'][0]


def rename_path(p):
    return PATH_RENAME.get(p, p)


def run(f, label, cat_of, alive, log):
    d = json.load(open(f, encoding='utf-8'))
    words = d['words']
    by = collections.defaultdict(list)
    for w in words:
        by[w['text']].append(w)

    # ── 0 · ตามชื่อกิ่งที่เปลี่ยนวันนี้ ──────────────────────────────
    n_ren = 0
    for w in words:
        ps = [rename_path(p) for p in paths_of(w)]
        if ps != paths_of(w):
            set_paths(w, ps, cat_of); n_ren += 1
    if n_ren:
        log.append('  [%s] ตามชื่อกิ่งที่เปลี่ยน %d รายการ' % (label, n_ren))

    # ── 1 · เพิ่มกิ่งก่อน ───────────────────────────────────────────────
    for item, txt, adds in ADD:
        for w in by.get(txt, []):
            cur = paths_of(w)
            new = [p for p in adds if p not in cur]
            if new:
                set_paths(w, cur + new, cat_of)
                log.append('  [%s] %-38s เพิ่ม %s' % (item, txt, ' · '.join(x.split(' / ')[-1] for x in new)))

    # ── 2 · แล้วค่อยถอนกิ่ง ─────────────────────────────────────────────────
    for item, txt, drops in DROP:
        for w in by.get(txt, []):
            cur = paths_of(w)
            keep = [p for p in cur if p not in drops]
            if len(keep) != len(cur):
                if not keep:
                    log.append('  🔴 [%s] %s จะเหลือ 0 กิ่ง — ไม่ถอน' % (item, txt)); continue
                set_paths(w, keep, cat_of)
                log.append('  [%s] %-38s ถอน %d กิ่ง' % (item, txt, len(cur) - len(keep)))

    # ── 3 · แก้ความหมาย ─────────────────────────────────────────────
    for item, txt, ms in MEANING:
        for w in by.get(txt, []):
            if 'meanings' in w:
                w['meanings'] = list(ms)
            w['meaning'] = ' · '.join(ms)
            log.append('  [%s] %-38s ความหมาย → %s' % (item, txt, w['meaning'][:46]))

    for item, txt, extra in MEANING_APPEND:
        for w in by.get(txt, []):
            ms = w.get('meanings') or ([w['meaning']] if w.get('meaning') else [])
            if extra not in ms:
                ms = ms + [extra]
            if 'meanings' in w:
                w['meanings'] = ms
            w['meaning'] = ' · '.join(ms)
            log.append('  [%s] %-38s ความหมาย + "%s"' % (item, txt, extra))

    # ── 4 · ยุบแถวซ้ำในเล่มเดียวกัน ────────────────────────────────
    for txt in MERGE_DUP:
        rows = by.get(txt, [])
        if len(rows) < 2:
            continue
        novels = {r.get('novel') for r in rows}
        if len(novels) > 1:
            log.append('  🔴 [4.2] %s ซ้ำข้ามเล่ม ห้ามยุบ' % txt); continue
        keep = rows[0]
        merged, seen = [], set()
        ms = []
        for r in rows:
            for p in paths_of(r):
                if p not in seen:
                    seen.add(p); merged.append(p)
            for m in (r.get('meanings') or ([r['meaning']] if r.get('meaning') else [])):
                if m not in ms:
                    ms.append(m)
        set_paths(keep, merged, cat_of)
        if 'meanings' in keep:
            keep['meanings'] = ms
        keep['meaning'] = ' · '.join(ms)
        for r in rows[1:]:
            words.remove(r)
        log.append('  [4.2] %-38s ยุบ %d แถว → 1 แถว · รวมได้ %d กิ่ง'
                   % (txt, len(rows), len(merged)))

    # ── 5 · เกลานิยามกิ่ง ───────────────────────────────────────────
    for b in d.get('branches', []):
        b['path'] = rename_path(b['path'])
        if b['path'] in DEF_FIX:
            b['definition'] = DEF_FIX[b['path']]
            log.append('  [7.2] เกลานิยามกิ่ง %s' % b['path'].split(' / ')[-1])

    # ── ด่านตรวจ ────────────────────────────────────────────────────
    err = []
    ghost = set()
    for w in words:
        for f2 in PF:
            v = w.get(f2)
            vs = [v] if isinstance(v, str) else (v or [])
            for p in vs:
                pp = p.get('path') if isinstance(p, dict) else p
                if pp and pp not in alive:
                    ghost.add(pp)
        if not paths_of(w):
            err.append('รายการไม่มีกิ่งเลย: %s' % w['text'])
    if ghost:
        err.append('กิ่งลอย %d เส้น เช่น %s' % (len(ghost), sorted(ghost)[:3]))
    return d, words, err


