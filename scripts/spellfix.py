import re


def yamok(t):
    """เว้นวรรครอบไม้ยมก · ทำทีละบรรทัด ไม่ยุ่งกับย่อหน้าและไม่ทิ้งช่องว่างท้ายบรรทัด"""
    if not isinstance(t, str) or 'ๆ' not in t:
        return t
    out = []
    for line in t.split('\n'):
        n = re.sub(r'[ \t]*ๆ[ \t]*', ' ๆ ', line)
        n = re.sub(r'ๆ +', 'ๆ ', n)
        n = re.sub(r' +ๆ', ' ๆ', n)
        ind = re.match(r'^[ \t]*', line).group(0)
        n = ind + n.lstrip(' ')
        out.append(n.rstrip() + (' ' if line.endswith(' ') else ''))
    return '\n'.join(out)


def fix(text):
    """แปลงข้อความจากไฟล์ประวัติ ให้เป็นรูปที่ใช้อยู่ในคลังตอนนี้
    (แก้สะกดตามทะเบียน + เว้นวรรคไม้ยมก)"""
    return yamok(SPELLFIX.get(text, text))
