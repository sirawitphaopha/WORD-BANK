def grp(w, p):
    keep = w.get('all_paths') or []
    kp = [k['path'] for k in keep]
    if any(k != p['path'] and k.startswith(p['path'] + ' / ') for k in kp):
        return 'ก'
    if any(k['category_id'] == p['category_id'] for k in keep):
        return 'ข'
    return 'ค'


def pattern(w):
    """คืนรหัสลวดลายของใบนี้ — เรียงตามน้ำหนักของหลักฐาน"""
    out = []
    if w.get('source') or w.get('source_others') or w.get('picked_from'):
        out.append('L1')
    if w.get('paths_added_this_round'):
        out.append('L2')
    if not out:
        out.append('L3')
    return out


