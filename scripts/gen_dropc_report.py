def grp(w, p):
    keep = w.get('all_paths') or []
    kp = [k['path'] for k in keep]
    if any(k != p['path'] and k.startswith(p['path'] + ' / ') for k in kp):
        return 'ก'
    if any(k['category_id'] == p['category_id'] for k in keep):
        return 'ข'
    return 'ค'


def main():
    D = json.load(open(RES))
    W = D['words']
    B = BranchBook()

    rows, counts = [], collections.Counter()
    for w in W:
        for p in (w.get('paths_dropped_this_round') or []):
            g = grp(w, p)
            counts[g] += 1
            if g == 'ค':
                rows.append((w, p))

    real = {(w['text'], p['path']) for w, p in rows}
    missing = [k for k in list(SUSPECT) + list(BORDERLINE) if k not in real]
    if missing:
        print('🛑 มีเส้นในตารางคำวินิจฉัยที่ไม่มีอยู่จริงในผลลัพธ์ — ไม่เขียนไฟล์')
        for m in missing:
            print('   ', m)
        sys.exit(1)

    # เรียง: ผิดก่อน (เลข 1-33) → ก้ำกึ่ง → ที่เหลือ (จัดกลุ่มตามกิ่งเพื่อให้อ่านต่อเนื่อง)
    def rank(t):
        w, p = t
        k = (w['text'], p['path'])
        if k in SUSPECT:
            return (0, p['path'], w['text'])
        if k in BORDERLINE:
            return (1, p['path'], w['text'])
        return (2, p['path'], w['text'])

    rows.sort(key=rank)
    n_susp = sum(1 for t in rows if (t[0]['text'], t[1]['path']) in SUSPECT)
    n_bord = sum(1 for t in rows if (t[0]['text'], t[1]['path']) in BORDERLINE)
    n_ok = len(rows) - n_susp - n_bord

    def split(line):
        """แยก 'ที่อยู่เต็ม  [รหัส]' ออกเป็น (ข้อความ, รหัส) เพื่อจัดสไตล์คนละแบบ"""
        if line.endswith(']') and '  [' in line:
            a, b = line.rsplit('  [', 1)
            return a, b[:-1]
        return line, ''

