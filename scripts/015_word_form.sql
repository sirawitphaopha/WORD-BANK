-- 015 · ช่อง word_form — คำนี้สร้างขึ้นมายังไง
--
-- 🎯 เจ้าของคลังเสนอเอง 3 ส.ค. 2569 หลังคุยเรื่องคำซ้อน
--    _"คำซ้อน เราบอกว่าจะทำนี่นา เราทำแบบไหนดี ติดแท็กชนิดใช่ไหมนะ"_
--
-- 🔑 ทำไมต้องเป็นช่องใหม่ ไม่ใช่ค่าใหม่ในช่อง kind เดิม
--    kind ตอบว่า "ยาวแค่ไหน"      → คำ · วลี · ประโยค
--    word_form ตอบว่า "สร้างยังไง" → คำซ้อน · คำซ้ำ · คำประสม · คำทับศัพท์
--    `หนั่นแน่น` เป็นทั้ง **คำ** และ **คำซ้อน** พร้อมกัน = คนละแกน
--    ถ้ายัดช่องเดียวกันต้องเลือกอย่างใดอย่างหนึ่ง แล้วเสียอีกอย่างไป
--
-- 🎯 ประโยชน์ที่ตั้งใจให้เกิด — กันตัวตรวจคำผิดทักผิด
--    คำซ้อนแบบไทยหน้าตาเหมือนคำพิมพ์ผิดมาก · ผู้ช่วยเคยทัก `หนั่นแน่น` ว่าผิด
--    ทั้งที่ `หนั่น` มีในพจนานุกรมแปลว่าแน่น เป็นคำซ้อนแบบไทยแท้
--    พอรู้ว่าคำไหนเป็นคำซ้อน ระบบจะลดน้ำหนักธงสงสัยลงเองได้
--
-- 📐 ที่เจ้าของคลังเคาะ: **ค่าเดียวต่อคำ · ปล่อยว่างได้** (ว่าง = ยังไม่ได้ดู ไม่ใช่ผิด)
--    4 ประเภทที่ใช้จริง — ตัดคำมูลกับคำสมาสออก เพราะไม่ช่วยงานเขียนนิยาย
--
-- 🛡 ไม่ลบ ไม่แก้ข้อมูลเดิมสักแถว · รันซ้ำได้ไม่พัง
-- ============================================================

alter table wb_words  add column if not exists word_form text;
alter table wb_review add column if not exists word_form text;

-- จำกัดค่าให้เหลือ 4 ประเภทที่เคาะไว้ (ค่าว่างยังใส่ได้ = ยังไม่ได้ดู)
-- ใช้ชื่อไทยตรง ๆ เพราะเป็นคำที่เจ้าของคลังอ่านเอง ไม่ต้องแปลกลับ
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'wb_words_word_form_ck') then
    alter table wb_words add constraint wb_words_word_form_ck
      check (word_form is null or word_form in ('คำซ้อน', 'คำซ้ำ', 'คำประสม', 'คำทับศัพท์'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'wb_review_word_form_ck') then
    alter table wb_review add constraint wb_review_word_form_ck
      check (word_form is null or word_form in ('คำซ้อน', 'คำซ้ำ', 'คำประสม', 'คำทับศัพท์'));
  end if;
end $$;

-- ไว้กรองดูทีละประเภทในหน้าคลังคำ
create index if not exists wb_words_word_form_idx on wb_words (word_form) where word_form is not null;

-- ── เติมย้อนหลังเฉพาะที่มั่นใจ 100% ──────────────────────────────
-- 🔒 เติมแค่ 2 กรณีที่เป็นกฎตายตัว ไม่ใช่การเดา
--    ที่เหลือปล่อยว่างไว้ให้ AI เติมตอนจัดคำ แล้วเจ้าของคลังแก้เองได้
--    (ตัวจับรูปแบบคำซ้อนด้วยเครื่องล้วนไม่แม่นพอ — ทดลองแล้วผิดเกินครึ่ง
--     เพราะภาษาไทยไม่มีช่องว่าง มันซอยคำผิด เช่น กรอกตา → กรอ + กตา)

-- ① คำซ้ำ — ลงท้ายด้วยไม้ยมก เป็นกฎตายตัว ไม่มีทางผิด
update wb_words set word_form = 'คำซ้ำ'
 where word_form is null and text ~ 'ๆ\s*$';

-- ② คำทับศัพท์ — คำที่อยู่หมวด 7 (คำทับศัพท์ที่มักสะกดผิด) อยู่แล้ว
update wb_words set word_form = 'คำทับศัพท์'
 where word_form is null and category_id = 'c6';


