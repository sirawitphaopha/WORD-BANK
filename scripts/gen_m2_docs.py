def final_paths(w, kept):
    """กิ่งที่คำนี้อยู่จริงในคลังตอนนี้ พร้อมป้ายว่ากิ่งไหนเดิม กิ่งไหนเพิ่งเพิ่ม

    🔑 อ่านจาก branches-data.json ตรง ๆ ไม่คำนวณเอง
       คอลัมน์นี้มีไว้ตอบคำถาม "สรุปแล้วคำนี้อยู่กิ่งอะไรบ้าง" ซึ่งตารางเดิมไม่เคยบอก
       จนพี่กันอ่านแล้วเข้าใจว่าการแย้ง = ปัดกิ่งใหม่ทิ้ง (27 ก.ค.)
    kept = กิ่งที่ผู้ช่วยขอถอนในแถวนี้ แต่ไม่ให้ถอน → ติดป้ายพิเศษให้เห็นว่าคือกิ่งไหน
    """
    was = {(x['c'], x['p']) for x in BEF[w]['paths']}
    out = []
    for c, p in sorted(NOWPATHS[w], key=lambda x: (NO.get(x[0], 99), x[1])):
        label = 'ม.%s › %s' % (NO.get(c, '?'), p)
        if (c, p) == kept:
            out.append(('keep', label, 'กิ่งเดิม · กิ่งที่ผู้ช่วยขอถอน แต่คงไว้'))
        elif (c, p) in was:
            out.append(('old', label, 'กิ่งเดิม'))
        else:
            out.append(('new', label, 'เพิ่มรอบนี้'))
    return out


def grouped():
    g = collections.defaultdict(list)
    for w, c, p, kind in ROWS:
        k, why = VERDICT[(w, c, p)]
        g[k].append((w, c, p, kind, why))
    for k in g:
        g[k].sort(key=lambda x: (x[0], x[2]))
    return g


