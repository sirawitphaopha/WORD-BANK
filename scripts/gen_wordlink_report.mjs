// สร้างรายงานผลตรวจเส้นโยง "คำเดี่ยว ↔ วลี"
// รัน: node scripts/gen_wordlink_report.mjs   (จากรากเรพ · เครื่องนี้ไม่มี Python จึงเขียนด้วย Node)
// อ่าน: docs/wordlink/pairs.json + out-1.jsonl + out-2.jsonl
// เขียน: docs/wordlink/REPORT.md
import fs from 'fs';

const D = 'docs/wordlink/';
const pairs = JSON.parse(fs.readFileSync(D + 'pairs.json', 'utf8'));
const P = new Map(pairs.map((p, i) => [i + 1, p]));
const read = (f) => fs.readFileSync(D + f, 'utf8').trim().split('\n').map((l) => JSON.parse(l));
const ans = [...read('out-1.jsonl'), ...read('out-2.jsonl')].sort((a, b) => a.n - b.n);

// ── ด่านตรวจ · ไม่ผ่าน = ไม่ยอมเขียนไฟล์ ────────────────────────────────
const OK = ['ตัดมา', 'เก็บแยก', 'ไม่แน่ใจ', 'ไม่เกี่ยวกัน'];
const err = [];
if (ans.length !== pairs.length) err.push(`จำนวนคำตอบ ${ans.length} ไม่เท่ากับโจทย์ ${pairs.length}`);
for (let i = 1; i <= pairs.length; i++) if (!ans.find((a) => a.n === i)) err.push(`ขาดข้อ ${i}`);
for (const a of ans) {
  if (!OK.includes(a.verdict)) err.push(`ข้อ ${a.n} คำตัดสินนอกรายการ`);
  if (!a.why || a.why.trim().length < 5) err.push(`ข้อ ${a.n} ไม่มีเหตุผลกำกับ`);
}
if (err.length) { console.error('🔴 ไม่ผ่านด่านตรวจ:'); err.slice(0, 20).forEach((e) => console.error('  ' + e)); process.exit(1); }

// ── นับ ────────────────────────────────────────────────────────────────
const by = (k) => ans.reduce((m, a) => ((m[a[k]] = (m[a[k]] || 0) + 1), m), {});
const g = by('verdict'), c = by('confidence');
const pick = (v) => ans.filter((a) => a.verdict === v);

// ข้อที่เอเจนต์เห็นต่างจากที่เครื่องจัดกลุ่มเบื้องต้น
const machineOf = (grp) => (grp === 'คนละเล่ม' || grp === 'จดห่างกัน' ? 'เก็บแยก' : grp === 'จดติดกัน' ? 'ตัดมา' : null);
const differ = ans.filter((a) => { const m = machineOf(P.get(a.n).group); return m && m !== a.verdict; });

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const line = (a) => {
  const p = P.get(a.n);
  const where = p.word_line && p.phrase_line ? `บรรทัด ${p.word_line} ↔ ${p.phrase_line}` : (p.word_novel !== p.phrase_novel ? 'คนละเล่ม' : '—');
  return `| ${a.n} | ${esc(p.word)} | ${esc(p.phrase)} | ${where} | ${a.confidence} | ${esc(a.why)} |`;
};
const table = (rows) => ['| ข้อ | คำ | วลีที่คำนั้นอยู่ข้างใน | ตำแหน่ง | มั่นใจ | เหตุผล |', '|---|---|---|---|---|---|', ...rows.map(line)].join('\n');

// ── เขียนรายงาน ────────────────────────────────────────────────────────
const notTaken = ans.filter((a) => a.verdict !== 'ตัดมา');   // เก็บแยก + ไม่เกี่ยวกัน = ไม่ได้ตัดมา
const out = `# 📄 ข้อ 1 · เส้นโยง "คำเดี่ยว ↔ วลี" — รายการทั้งหมด 450 คู่

**12 ส.ค. 2569**

## 🎯 ข้อ 1 ทำไปเพื่ออะไร

ในคลังมี **คำเดี่ยว** กับ **วลี** อยู่ปนกัน บางคู่เป็นของชิ้นเดียวกัน (เจ้าของคลังจดวลีก่อน แล้วแตกคำออกมา)
แต่คลังเก็บสองอันนี้เป็นคนละใบ ไม่มีอะไรบอกว่าเกี่ยวกัน

**เป้าหมายคือ เปิดหน้ารายละเอียดคำในเว็บแล้วเห็นว่าคำนั้นตัดมาจากวลีไหน กดกลับไปดูวลีเต็มได้**

## 📍 ทำถึงไหนแล้ว

| | จำนวน | สถานะ |
|---|---|---|
| ค้นเจอคู่ที่ยังไม่มีเส้นโยง | 450 | ✅ |
| ผู้ช่วย 2 ตัวตรวจทีละคู่ + เครื่องตรวจซ้ำ | 450 | ✅ |
| **ตัดมาจากกันจริง → โยงลงคลังแล้ว** | **${g['ตัดมา'] || 0}** | ✅ **โยงแล้ว** |
| **ไม่ได้ตัดมา** | **${notTaken.length}** | ⏳ **ยังไม่ตัดสินว่าจะเอายังไง** |
| เก็บกวาดเส้นเดิมที่เสียอยู่ในคลัง | 10 | ✅ ลบแล้ว |

**ผลต่อคลัง** — เส้นโยงในคลัง 1,170 → **1,311 เส้น** (เพิ่ม 151 · ลบของเสีย 10)
วลีที่มีคำลูกโยงถึง 675 → **814 จาก 1,407** · จำนวนคำเท่าเดิม 2,809 คำ ไม่หายสักคำ

## ⏳ เหลือเรื่องเดียว — ${notTaken.length} คู่ที่ไม่ได้ตัดมา จะเอายังไง

พวกนี้คือคำที่เก็บมาต่างหากจริง ๆ **แค่บังเอิญไปโผล่อยู่ในวลีอื่นด้วย**
เช่นเก็บคำว่า \`ครุ่นคิด\` มาจากที่หนึ่ง แล้ววันหลังไปเก็บวลี \`[ชื่อคน] ครุ่นคิดชั่วขณะ\` มาจากอีกที่

| ทาง | ผลที่ตามมา |
|---|---|
| **1 · ทิ้งไปเลย** | ไม่โยงอะไรทั้งนั้น — **ข้อ 1 ปิดได้ทันที** |
| **2 · เก็บไว้เป็นอีกแบบ** | โยงไว้แต่ติดป้ายคนละชนิด ("คำนี้โผล่ในวลีนี้ด้วย" ไม่ใช่ "ตัดมาจากวลีนี้") · เปิดหน้ารายละเอียดคำจะเห็นวลีอื่นที่มีคำนี้อยู่ · ต้องเพิ่มป้ายชนิดใหม่ในระบบ |

---

## ✅ ${g['ตัดมา'] || 0} คู่ที่โยงลงคลังไปแล้ว

${table(pick('ตัดมา'))}

---

## ⏳ ${notTaken.length} คู่ที่ไม่ได้ตัดมา — รอตัดสิน

${table(notTaken)}

---

## 📎 ภาคผนวก · ${differ.length} ข้อที่ผู้ช่วยเห็นต่างจากที่เครื่องจัดกลุ่มไว้ตอนแรก

เครื่องดูแค่ตำแหน่งบรรทัดกับชื่อเล่ม ส่วนผู้ช่วยเปิดทะเบียนการสกัดของคลังประกอบด้วย

${table(differ)}

---

*ตรวจด้วยเครื่องผ่านครบ — ตอบครบ 450 ข้อ · ไม่มีข้อขาด · ไม่มีข้อซ้ำ · ทุกข้อมีเหตุผลกำกับ*
*ความมั่นใจของผู้ช่วย — สูง ${c['สูง'] || 0} · กลาง ${c['กลาง'] || 0} · ต่ำ ${c['ต่ำ'] || 0}*
`;

fs.writeFileSync(D + 'REPORT.md', out, 'utf8');
console.log('✅ เขียน docs/wordlink/REPORT.md แล้ว');
console.log(`   ตัดมา ${g['ตัดมา'] || 0} · เก็บแยก ${g['เก็บแยก'] || 0} · ไม่เกี่ยวกัน ${g['ไม่เกี่ยวกัน'] || 0} · เห็นต่างจากเครื่อง ${differ.length}`);
